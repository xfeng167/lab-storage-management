ROLE_VIEWER = "viewer"
ROLE_STAFF = "staff"
ROLE_ADMIN = "admin"

PERMISSION_MATERIAL_READ = "material:read"
PERMISSION_LOCATION_READ = "location:read"
PERMISSION_ORDER_CREATE = "order:create"
PERMISSION_ORDER_READ_OWN = "order:read_own"
PERMISSION_ORDER_CANCEL_OWN = "order:cancel_own"
PERMISSION_ORDER_ARCHIVE_OWN = "order:archive_own"
PERMISSION_CATALOG_MANAGE = "catalog:manage"
PERMISSION_REPORT_READ = "report:read"
PERMISSION_INVENTORY_MANAGE = "inventory:manage"
PERMISSION_ORDER_REVIEW = "order:review"
PERMISSION_ORDER_READ_ALL = "order:read_all"
PERMISSION_AUDIT_READ = "audit:read"
PERMISSION_USER_MANAGE = "user:manage"

REQUESTER_PERMISSIONS = frozenset(
    {
        PERMISSION_MATERIAL_READ,
        PERMISSION_LOCATION_READ,
        PERMISSION_ORDER_CREATE,
        PERMISSION_ORDER_READ_OWN,
        PERMISSION_ORDER_CANCEL_OWN,
        PERMISSION_ORDER_ARCHIVE_OWN,
    }
)

ROLE_PERMISSIONS = {
    ROLE_VIEWER: REQUESTER_PERMISSIONS,
    ROLE_STAFF: REQUESTER_PERMISSIONS
    | {
        PERMISSION_CATALOG_MANAGE,
        PERMISSION_REPORT_READ,
    },
    ROLE_ADMIN: REQUESTER_PERMISSIONS
    | {
        PERMISSION_CATALOG_MANAGE,
        PERMISSION_REPORT_READ,
        PERMISSION_INVENTORY_MANAGE,
        PERMISSION_ORDER_REVIEW,
        PERMISSION_ORDER_READ_ALL,
        PERMISSION_AUDIT_READ,
        PERMISSION_USER_MANAGE,
    },
}


def role_has_permission(role: str, permission: str) -> bool:
    return permission in ROLE_PERMISSIONS.get(role, frozenset())
